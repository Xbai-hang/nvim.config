------------------------------------------------------------------------------
-- 1. Leader 键
------------------------------------------------------------------------------
vim.g.mapleader = " " -- 全局 Leader 键
vim.g.maplocalleader = " " -- 局部映射的 Leader 键

------------------------------------------------------------------------------
-- 2. 文件安全
------------------------------------------------------------------------------
vim.o.confirm = true -- 操作可能丢失未保存内容时请求确认

------------------------------------------------------------------------------
-- 3. 光标与滚动
------------------------------------------------------------------------------
-- Normal/Visual/Terminal 使用方块，Insert 使用粗竖线，Replace 使用粗横线。
vim.opt.guicursor = {
  "n-v-c:block",
  "i-ci-ve:ver60",
  "r-cr:hor60",
  "o:hor60",
  "t:block",
}
vim.o.scrolloff = 8 -- 光标上下保留 8 行空间
vim.o.sidescrolloff = 8 -- 水平滚动时左右保留 8 列空间
vim.opt.whichwrap:append("<,>,[,]") -- 允许左右方向键跨越行首和行尾

------------------------------------------------------------------------------
-- 4. 行号与指示列
------------------------------------------------------------------------------
vim.wo.number = false -- 默认隐藏行号；<leader>ul 可切换显示
vim.wo.relativenumber = false -- 不显示相对行号
vim.wo.cursorline = false -- 不高亮当前行
vim.opt.signcolumn = "yes" -- 始终保留一列 Git/诊断标记
vim.wo.foldcolumn = "1" -- 始终保留一列折叠状态
vim.o.statuscolumn = "%=%l%s%C" -- 左侧依次显示行号、状态标记和折叠状态

------------------------------------------------------------------------------
-- 5. 代码折叠
------------------------------------------------------------------------------
vim.opt.foldenable = true -- 允许折叠
vim.o.foldlevel = 99 -- 当前窗口默认展开全部层级
vim.o.foldlevelstart = 99 -- 新打开的文件默认展开全部层级
vim.opt.fillchars:append({ foldopen = "", foldclose = "", foldsep = " " }) -- 折叠列图标

------------------------------------------------------------------------------
-- 6. 默认缩进
------------------------------------------------------------------------------
-- 默认使用 4 个空格；特定语言由 after/ftplugin 覆盖。
vim.opt.tabstop = 4 -- Tab 的显示宽度
vim.opt.softtabstop = 4 -- 插入或删除缩进时的宽度
vim.o.shiftround = true -- >> << 时对齐到 shiftwidth 的倍数
vim.opt.shiftwidth = 4 -- 自动缩进和 >> << 的宽度
vim.opt.expandtab = true -- 输入 Tab 时插入空格
vim.o.autoindent = true -- 自动继承上一行缩进

------------------------------------------------------------------------------
-- 7. 搜索
------------------------------------------------------------------------------
vim.o.ignorecase = true -- 搜索时忽略大小写
vim.o.smartcase = true -- 搜索词包含大写字母时区分大小写
vim.o.hlsearch = true -- 高亮搜索结果
vim.o.incsearch = true -- 边输入边搜索

------------------------------------------------------------------------------
-- 8. 响应延迟
------------------------------------------------------------------------------
vim.o.updatetime = 300 -- CursorHold 和部分插件刷新的等待时间（毫秒）
vim.o.timeoutlen = 500 -- 等待快捷键组合后续按键的时间（毫秒）

------------------------------------------------------------------------------
-- 9. 窗口与折行
------------------------------------------------------------------------------
vim.o.splitbelow = true -- 水平分屏在下方打开
vim.o.splitright = true -- 垂直分屏在右侧打开
vim.opt.wrap = false -- 代码默认不折行；文档类文件由 after/ftplugin 覆盖

------------------------------------------------------------------------------
-- 10. 鼠标
------------------------------------------------------------------------------
vim.o.mouse = "a" -- 启用鼠标支持

------------------------------------------------------------------------------
-- 11. 文件恢复与 Undo
------------------------------------------------------------------------------
vim.o.backup = false -- 不保留写入前的备份副本
vim.opt.undofile = true -- 重启 Neovim 后仍可撤销历史修改
vim.opt.swapfile = false -- 不创建崩溃恢复用的交换文件

------------------------------------------------------------------------------
-- 12. 补全与模式提示
------------------------------------------------------------------------------
vim.opt.shortmess:append("c") -- 补全菜单显示时隐藏冗余提示
vim.o.pumheight = 10 -- 补全菜单最多显示 10 项
vim.o.showmode = false -- 当前模式由 Lualine 显示

------------------------------------------------------------------------------
-- 13. 颜色与空白字符
------------------------------------------------------------------------------
vim.o.termguicolors = true -- 启用 24 位色
vim.o.list = false -- 默认隐藏空白字符；<leader>uw 可切换显示
vim.opt.listchars = {
  space = "·", -- 普通空格
  tab = "╶─→", -- Tab（首字符、填充字符、尾字符）
  trail = "·", -- 行尾空格
  nbsp = "␣", -- 不换行空格
}

------------------------------------------------------------------------------
-- 14. 系统剪切板
------------------------------------------------------------------------------
vim.opt.clipboard = "unnamedplus" -- 复制和粘贴使用系统剪贴板
